def _canon(index: dict[str, Any]) -> str:
    """Golden comparison text: VOLATILE keys dropped, and the safety roots' resolved paths (also
    checkout-specific) blanked; NaN CIs compare as text."""
    keep = {k: v for k, v in index.items() if k not in VOLATILE}
    if "safety" in keep:
        keep["safety"] = {
            f: {**s, "meta": [{**m, "root": None} for m in s["meta"]]}
            for f, s in keep["safety"].items()
        }
    return json.dumps(keep, sort_keys=True)



def test_v4_synthetic_golden_reproduced_exactly():
    """Generated by scripts/index/build_v4_fixture.py from the pre-v5 index.py (merge base)."""
    methods = ix.load_methods(V4_FIX / "methods.json")
    golden = json.loads((V4_FIX / "golden" / "index.json").read_text())
    for built in (
        ix.build_index(_v4_sources(), methods, version="v4"),
        ix.build_index(_v4_sources(), methods),  # the library default stays v4
    ):
        assert built["version"] == "hindex-v4"
        assert _canon(built) == _canon(golden)
        assert ix.render_md(built) == (V4_FIX / "golden" / "index.md").read_text()


def _pinned_roots_v4(golden: dict[str, Any], tmp: Path) -> dict[str, list[Path]]:
    """Mirrors of a hindex-v4 golden's source roots holding only its arms, over v4's families:
    claim families symlink arm dirs, sibling filters the units files to its methods, and a safety
    root keeps the ``index_counts.jsonl`` rows of its arms plus ``index_meta.json``."""
    arms = {f: {a for m in golden["methods"].values() for a in m[f]} for f in ix.FAMILIES}
    out: dict[str, list[Path]] = {}
    for f, roots in golden["sources"].items():
        out[f] = []
        for k, root in enumerate(map(Path, roots)):
            mirror = tmp / f / str(k)
            mirror.mkdir(parents=True)
            out[f].append(mirror)
            if f == ix.SIBLING:
                for dom, src in ix.um_paths(root).items():
                    if not src.exists():
                        continue
                    dst = ix.um_paths(mirror)[dom]
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    keep = [
                        ln
                        for ln in src.read_text(encoding="utf-8").splitlines(keepends=True)
                        if json.loads(ln)["method"] in arms[f]
                    ]
                    dst.write_text("".join(keep), encoding="utf-8")
            elif f in ix.SAFETY_FAMILIES:
                with (
                    open(root / ix.SAFETY_COUNTS, encoding="utf-8") as src_fh,
                    open(mirror / ix.SAFETY_COUNTS, "w", encoding="utf-8") as dst_fh,
                ):
                    for ln in src_fh:
                        if ln.strip() and json.loads(ln)["arm"] in arms[f]:
                            dst_fh.write(ln)
                if (root / ix.SAFETY_META).is_file():
                    (mirror / ix.SAFETY_META).write_bytes((root / ix.SAFETY_META).read_bytes())
            else:
                for a in sorted(arms[f]):
                    if (root / a / ix.CELLS).is_file():
                        (mirror / a).symlink_to(root / a)
    return out


def _devbox_golden() -> dict[str, Any]:
    golden = json.loads((FIX / "index_v4_devbox.json").read_text())
    roots = [Path(r) for rs in golden["sources"].values() for r in rs]
    if missing := [r for r in roots if not r.is_dir()]:
        pytest.skip(f"dev-box sources absent: {missing[:2]}")
    return golden


def _golden_methods(golden: dict[str, Any]) -> ix.Methods:
    return ix.Methods(
        methods={m: {f: list(a) for f, a in fams.items()} for m, fams in golden["methods"].items()},
        exclude=set(golden["exclude"]),
        notes=ix.load_methods(cli.INDEX_METHODS).notes,
    )


def test_v4_devbox_golden_reproduced_exactly(tmp_path):
    """The official hindex-v4 run (#42; index.py / methods.json unchanged since)."""
    golden = _devbox_golden()
    built = ix.build_index(
        _pinned_roots_v4(golden, tmp_path), _golden_methods(golden), workers=8, version="v4"
    )
    assert _canon(built) == _canon(golden)
    assert ix.render_md(built) == (FIX / "index_v4_devbox.md").read_text()



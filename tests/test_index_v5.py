# ---------------------------------------------------------------- the candidate rule


def _seg(readout: int, start: int, end: int, leaf: str) -> dict[str, Any]:
    return {"readout": readout, "start": start, "end": end, "leaf": leaf}


def _ment(readout: int, start: int, end: int) -> dict[str, Any]:
    return {"readout": readout, "start": start, "end": end}


def _am(
    item: str, layer: int, segs: list[dict], ments: list[dict], ok: bool = True
) -> dict[str, Any]:
    return {
        "id": item,
        "layer": layer,
        "map_status": "ok" if ok else "failed",
        "map": {"segments": segs},
        "mentions": ments,
    }


# layer 20, i1: mentions [9, 15) + [14, 25) of readout 0 merge to [9, 25).
#   [0, 10) false_claim overlaps by 1 char -> candidate (hallucinated)
#   [10, 20) correct inside -> candidate; [25, 30) detail touches (end == 25) -> not
#   readout 1 [0, 10) false_claim: no mention in readout 1 -> not; [12, 18) non_claim: not a claim
# layer 20, i2: one false claim [0, 50), mention at [100, 110) -> a zero row
# layer 20, i3: map failed -> not an item. layer 24, i1: mentions miss every claim -> absent
AM_CELLS = [
    _am(
        "i1",
        20,
        [
            _seg(0, 0, 10, "false_claim"),
            _seg(0, 10, 20, "correct"),
            _seg(0, 25, 30, "detail"),
            _seg(1, 0, 10, "false_claim"),
            _seg(0, 12, 18, "non_claim"),
        ],
        [_ment(0, 14, 25), _ment(0, 9, 15)],
    ),
    _am("i2", 20, [_seg(0, 0, 50, "false_claim")], [_ment(0, 100, 110)]),
    _am("i3", 20, [_seg(0, 0, 50, "false_claim")], [_ment(0, 0, 50)], ok=False),
    _am("i1", 24, [_seg(0, 0, 10, "detail")], [_ment(0, 10, 20), _ment(1, 0, 10)]),
]


def _write_cells(root: Path, arm: str, cells: list[dict[str, Any]]) -> Path:
    (root / arm).mkdir(parents=True)
    (root / arm / ix.CELLS).write_text("".join(json.dumps(c) + "\n" for c in cells))
    return root / arm / ix.CELLS


def test_is_candidate_overlap_rule():
    spans = {0: [(9, 25)]}
    assert ix.is_candidate(_seg(0, 0, 10, "x"), spans)  # 1 char
    assert not ix.is_candidate(_seg(0, 0, 9, "x"), spans)  # touching at the start
    assert not ix.is_candidate(_seg(0, 25, 30, "x"), spans)  # touching at the end
    assert ix.is_candidate(_seg(0, 24, 30, "x"), spans)
    assert not ix.is_candidate(_seg(1, 10, 20, "x"), spans)  # another readout
    assert ix.is_candidate(_seg(0, 0, 100, "x"), spans)  # containing


def test_claim_rows_candidates(tmp_path):
    p = _write_cells(tmp_path, "a", AM_CELLS)
    rows = ix.claim_rows(p, ix.AM, am_candidates=True)
    assert sorted(rows) == [20, 24]
    m20 = rows[20]
    assert m20.shape == (2, ix.N_COLS_CANDIDATES)  # i1, i2 (i3 unmapped)
    i1, i2 = m20
    assert (i1[ix.C_CLAIMS], i1[ix.C_FC], i1[ix.C_DET], i1[ix.C_ALL_CLAIMS]) == (2, 1, 0, 4)
    assert (i2[ix.C_CLAIMS], i2[ix.C_ALL_CLAIMS]) == (0, 1)  # a zero row, kept
    # readout / segment health columns: unchanged from the all-claims reader
    base = ix.claim_rows(p, ix.AM)
    assert base[20].shape == (2, ix.N_COLS)
    cols = [ix.C_READOUTS, ix.C_SEGMENTS]
    assert np.array_equal(m20[:, cols], base[20][:, cols])
    assert (base[20][0][ix.C_CLAIMS], base[20][1][ix.C_CLAIMS]) == (4, 1)
    r = ix.claim_metric(m20, ix.AM)
    assert r is not None and (r["v"], r["n"], r["n_items"]) == (0.5, 2, 2)
    assert ix.claim_metric(rows[24], ix.AM) is None  # 0 candidates: absent
    # the flag only applies to AM
    for fam in (ix.MAIN, ix.STORY):
        assert ix.claim_rows(p, fam, am_candidates=True) == {}  # AM-shaped cells: not mapped
    chat = [{"id": "c", "layer": 20, "stages": {"map": "ok"}, "map": AM_CELLS[0]["map"]}]
    q = _write_cells(tmp_path, "chat", chat)
    assert ix.claim_rows(q, ix.MAIN, am_candidates=True)[20].shape == (1, ix.N_COLS)


def test_merged_mentions_count_once(tmp_path):
    """Overlapping mentions merge: a claim overlapping both is one candidate, and a claim
    overlapping only their union (the gap is covered by the other one) is a candidate."""
    cells = [
        _am(
            "i1",
            20,
            [_seg(0, 4, 6, "false_claim"), _seg(0, 13, 15, "detail")],
            [_ment(0, 0, 10), _ment(0, 5, 14)],
        )
    ]
    (row,) = ix.claim_rows(_write_cells(tmp_path, "a", cells), ix.AM, am_candidates=True)[20]
    assert (row[ix.C_CLAIMS], row[ix.C_FC], row[ix.C_DET]) == (2, 1, 1)


# ---------------------------------------------------------------- v5 build


def _sources_v5(tmp: Path) -> dict[str, list[Path]]:
    chat = {"stages": {"map": "ok"}}
    seg = {"readout": 0, "leaf": "false_claim"}
    ok = {"readout": 0, "leaf": "correct"}
    for fam, layers in (("main", (20, 24)), ("story", (20, 24))):
        cells = [{"id": "i1", "layer": L, "map": {"segments": [seg, ok]}, **chat} for L in layers]
        _write_cells(tmp / fam, "jlens", cells)
    _write_cells(tmp / "am", "jlens", AM_CELLS)
    for d, p in ix.um_paths(tmp / "um").items():
        p.parent.mkdir(parents=True, exist_ok=True)
        us = [
            {
                "method": "jlens",
                "item": f"{d}{k}",
                "layer": L,
                "committed": True,
                "probe": {"na_reason": None, "fire_L": k == 0},
                "cross": [],
            }
            for L in (20, 24)
            for k in range(2)
        ]
        p.write_text("".join(json.dumps(u) + "\n" for u in us))
    (tmp / "or").mkdir()
    rows = [
        {
            "arm": "jlens",
            "layer": L,
            "item": f"o{k}",
            "cluster": f"o{k}",
            **dict.fromkeys(ix.SAFETY_INT_COLS, 0),
            "n_claims": 1,
            "n_false": int(k == 0),
            "n_contradicted": int(k == 0),
        }
        for L in (20, 24)
        for k in range(4)
    ]
    (tmp / "or" / ix.SAFETY_COUNTS).write_text("".join(json.dumps(r) + "\n" for r in rows))
    return {
        ix.MAIN: [tmp / "main"],
        ix.AM: [tmp / "am"],
        ix.STORY: [tmp / "story"],
        ix.SIBLING: [tmp / "um"],
        ix.OVERREFUSAL: [tmp / "or"],
    }


def test_v5_am_on_candidates_rest_identical(tmp_path):
    src = _sources_v5(tmp_path)
    methods = ix.Methods(notes={"k": "methods note"})
    v4 = ix.build_index(src, methods, version="v4")
    v5 = ix.build_index(src, methods, version="v5")
    assert v5["version"] == "hindex-v5"
    assert v5["notes"] == {"k": "methods note", **ix.NOTES_V5}
    assert v4["notes"] == {"k": "methods note"}
    r4 = {r["layer"]: r for r in v4["rows"]}
    r5 = {r["layer"]: r for r in v5["rows"]}
    assert sorted(r5) == [20, 24]
    for L in (20, 24):
        for f in (ix.MAIN, ix.STORY, ix.SIBLING, ix.OVERREFUSAL):  # bit-identical to v4
            assert r5[L]["families"][f] == r4[L]["families"][f]
    am4, am5 = r4[20]["families"][ix.AM], r5[20]["families"][ix.AM]
    assert (am4["v"], am4["n"]) == (0.8, 5) and "n_all_claims" not in am4
    assert (am5["v"], am5["n"], am5["n_items"], am5["n_all_claims"]) == (0.5, 2, 2, 5)
    per = r5[20]["families"]
    for key, fams in (
        ("full", ix.FAMILIES),
        ("matched", ix.MATCHED),
        ("full_v3", ix.FAMILIES_V3),
        ("matched_v3", ix.MATCHED_V3),
    ):
        assert json.dumps(r5[20][key]) == json.dumps(ix.weighted_macro(per, fams))  # NaN CIs
        assert r5[20][key]["v"] != r4[20][key]["v"]
    # L24: AM has mapped cells but 0 candidate claims -> absent, and every macro with AM drops
    assert ix.AM in r4[24]["families"] and ix.AM not in r5[24]["families"]
    gone = {"arm": "jlens", "absent_reason": ix.ABSENT_NO_CANDIDATES}
    assert r5[24]["absent"] == {ix.AM: gone}
    assert not {"full", "matched", "full_v3", "matched_v3"} & set(r5[24])
    assert "absent" not in r4[24]
    md = ix.render_md(v5)
    assert md.startswith("# Hallucination index (hindex-v5)")
    assert "candidate claims" in md and "with v5 family definitions" in md
    assert "hindex-v3's" not in md
    assert "jlens.agentic_misalignment@24 (0 candidate claims)" in md
    assert "| method | layer | full | matched | full_v3 | main |" in md


def test_cli_default_is_v5(tmp_path, monkeypatch):
    for var in ix.SAFETY_ENV.values():
        monkeypatch.delenv(var, raising=False)
    src = _sources_v5(tmp_path / "src")
    (tmp_path / "methods.json").write_text("{}")
    argv = ["index", "--out", str(tmp_path / "none"), "--methods", str(tmp_path / "methods.json")]
    for fam, flag in (
        (ix.MAIN, "--main-root"),
        (ix.AM, "--am-root"),
        (ix.STORY, "--story-root"),
        (ix.SIBLING, "--um-root"),
        (ix.OVERREFUSAL, "--overrefusal-root"),
    ):
        argv += [flag, str(src[fam][0])]
    assert cli.main([*argv, "--dest", str(tmp_path / "d")]) == 0
    out = json.loads((tmp_path / "d" / "index.json").read_text())
    assert out["version"] == "hindex-v5"
    assert out["rows"][0]["families"][ix.AM]["v"] == 0.5
    assert cli.main([*argv, "--version", "v4", "--dest", str(tmp_path / "d4")]) == 0
    assert json.loads((tmp_path / "d4" / "index.json").read_text())["version"] == "hindex-v4"
    with pytest.raises(SystemExit, match="hindex-v4 only"):
        cli.main([*argv, "--version", "v3"])
    with pytest.raises(SystemExit):
        cli.main([*argv, "--version", "v6"])


# ---------------------------------------------------------------- cross-check against PR #43


def _am_candidate_script() -> ModuleType:
    path = REPO_ROOT / "scripts" / "index" / "am_candidate_claims.py"
    spec = importlib.util.spec_from_file_location("am_candidate_claims", path)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _crosscheck_arm(job: tuple[str, Path]) -> tuple[str, dict[int, Any], dict[int, Any]]:
    """(arm, #43 variant-(a) metrics per layer, v5 metrics per layer) for one AM arm."""
    arm, d = job
    mod = _am_candidate_script()
    rows, _ = mod.arm_rows(d / ix.CELLS, set())
    ref = {L: ix.claim_metric(m, ix.AM) for L, m in rows["all"].items()}
    _, _, mine, none = ix._claim_job((ix.AM, arm, d, True))
    return arm, ref, {**mine, **dict.fromkeys(none)}


def test_v5_am_matches_pr43_variant_a(tmp_path):
    golden = _devbox_golden()
    am_arms = sorted({a for m in golden["methods"].values() for a in m[ix.AM]})
    dirs = ix._arm_dirs(ix.AM, [Path(r) for r in golden["sources"][ix.AM]])
    jobs = [(a, dirs[a]) for a in am_arms if a in dirs]
    assert len(jobs) == len(am_arms)
    with Pool(min(8, len(jobs))) as pool:
        done = pool.map(_crosscheck_arm, jobs, chunksize=1)
    by_arm = {}
    for arm, ref, mine in done:
        assert ref.keys() == mine.keys(), arm
        for L, r in ref.items():
            m = mine[L]
            if r is None:
                assert m is None, (arm, L)
                continue
            assert m is not None, (arm, L)
            for k in ("v", "ci", "n", "n_items"):
                assert m[k] == r[k], (arm, L, k)
        by_arm[arm] = mine
    # and build_index carries them into the rows (AM roots only, pinned to the golden's arms)
    src = _pinned_roots_v4({**golden, "sources": {ix.AM: golden["sources"][ix.AM]}}, tmp_path)
    built = ix.build_index(src, _golden_methods(golden), workers=8, version="v5")
    n = 0
    for row in built["rows"]:
        if (am := row["families"].get(ix.AM)) is not None:
            ref = by_arm[am["arm"]][row["layer"]]
            assert {k: am[k] for k in ("v", "ci", "n", "n_items")} == {
                k: ref[k] for k in ("v", "ci", "n", "n_items")
            }
            n += 1
    assert n > 0


def test_report_never_overwrites_an_index_of_another_version(tmp_path, monkeypatch, capsys):
    """`hbench report` refreshes a v4 index; it must not clobber `hbench index`'s v5 one."""
    for var in ix.SAFETY_ENV.values():
        monkeypatch.delenv(var, raising=False)
    monkeypatch.setattr(cli, "_cmd_report", lambda args: 3)
    chat = {"id": "i1", "layer": 20, "stages": {"map": "ok"}}
    chat["map"] = {"segments": [{"readout": 0, "leaf": "detail"}]}
    _write_cells(tmp_path / "wsbench_chat" / cli.DEFAULT_MODEL, "a", [chat])
    dest = tmp_path / "index" / cli.DEFAULT_MODEL
    dest.mkdir(parents=True)
    v5 = {"version": "hindex-v5", "rows": []}
    (dest / "index.json").write_text(json.dumps(v5))
    (dest / "index.md").write_text("v5 md\n")
    assert cli.main(["report", "--out", str(tmp_path)]) == 3  # report's own code is kept
    assert json.loads((dest / "index.json").read_text()) == v5
    assert (dest / "index.md").read_text() == "v5 md\n"
    assert "not written" in capsys.readouterr().out
    # an index of the same version (v4) is refreshed as before
    (dest / "index.json").write_text(json.dumps({"version": "hindex-v4", "rows": []}))
    assert cli.main(["report", "--out", str(tmp_path)]) == 3
    out = json.loads((dest / "index.json").read_text())
    assert out["version"] == "hindex-v4" and [(r["method"], r["layer"]) for r in out["rows"]] == [
        ("a", 20)
    ]
